const CUISINES = [
  "средиземноморская", "азиатская", "мексиканская", "домашняя простая",
  "ближневосточная", "европейская", "индийская", "скандинавская", "французская"
];

// Небольшой рандом в промпте, чтобы одинаковые по смыслу запросы не сходились
// каждый раз к одним и тем же «дежурным» блюдам.
export function randomCuisineHint(): string {
  return CUISINES[Math.floor(Math.random() * CUISINES.length)];
}
